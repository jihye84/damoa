def _has_jong(text):
    t = str(text).strip()
    if '/' in t:                      # 분수 a/b는 'b분의 a'로 읽어서 분자가 끝소리
        t = t.split('/')[0].split()[-1]
    t = t.replace(',', '')
    if not t or not t[-1].isdigit():
        return False
    if '.' in t:                      # 소수는 마지막 숫자를 하나씩 읽어요
        return t[-1] in '01678' or t[-1] == '3'
    n = int(t)
    if n == 0:
        return True
    if n % 10:
        return n % 10 in (1, 3, 6, 7, 8)
    if n % 100:
        return True                   # 십
    if n % 1000:
        return True                   # 백
    return True                       # 천, 만


def gwa(n): return '과' if _has_jong(n) else '와'
def eul(n): return '을' if _has_jong(n) else '를'
def eun(n): return '은' if _has_jong(n) else '는'


def mixed(whole, num, den):
    return f'{whole}{gwa(whole)} {num}/{den}'

bundles = []


def bundle(grade, term, unit, items, note=''):
    bid = f'math-{grade}-{term}-{len([b for b in bundles if b["grade"] == grade and b["term"] == term]) + 1}'
    bundles.append({
        'id': bid, 'subject': '수학', 'grade': grade, 'term': term, 'unit': unit,
        'title': f'수학 {grade}-{term} · {unit}', 'note': note, 'items': items,
    })


def add_pairs(n, lo_a, hi_a, lo_b, hi_b, cond):
    out, tries = [], 0
    while len(out) < n and tries < 5000:
        tries += 1
        a, b = R.randint(lo_a, hi_a), R.randint(lo_b, hi_b)
        if cond(a, b) and (a, b) not in out:
            out.append((a, b))
    return out


