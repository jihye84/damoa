def choice(title, q, correct, wrongs):
    """4지선다: correct 1개 + 서로 다른 오답 3개, 순서는 섞어요."""
    correct = str(correct)
    seen, opts = {correct}, []
    for w in wrongs:
        w = str(w)
        if w not in seen:
            seen.add(w)
            opts.append(w)
        if len(opts) == 3:
            break
    # 오답이 모자라면 정답 근처 수로 채워요 (음수는 안 씀)
    import re
    m = re.match(r'^(\d+)(\D*)$', correct)
    if len(opts) < 3 and m:
        n, suffix = int(m.group(1)), m.group(2)
        for d in (2, -2, 3, -3, 4, -4, 5, 6, 7, 11):
            v = f'{n + d}{suffix}'
            if n + d >= 0 and v not in seen:
                seen.add(v)
                opts.append(v)
            if len(opts) == 3:
                break
    assert len(opts) == 3, (title, q, correct, wrongs)
    options = opts + [correct]
    R.shuffle(options)
    return {
        'title': title,
        'kind': 'choice4',
        'content': {'kind': 'choice4', 'question': q, 'options': options},
        'answer_key': {'correct': options.index(correct)},
    }


def blank(title, q):
    return {'title': title, 'kind': 'blank', 'content': {'kind': 'blank', 'question': q}, 'answer_key': None}


def essay(title, q):
    return {'title': title, 'kind': 'essay', 'content': {'kind': 'essay', 'question': q}, 'answer_key': None}


def near(n, lo=0, hi=None, spread=(1, 2, 10)):
    """정답 근처의 그럴듯한 오답들"""
    out = []
    for d in spread:
        for s in (1, -1):
            v = n + s * d
            if v >= lo and (hi is None or v <= hi) and v != n:
                out.append(v)
    R.shuffle(out)
    return out


def num_kor(n):
    """수를 한자어로 읽기 (0~9999)"""
    digits = '영일이삼사오육칠팔구'
    if n == 0:
        return '영'
    out = ''
    for unit, name in ((1000, '천'), (100, '백'), (10, '십'), (1, '')):
        d = n // unit % 10
        if d:
            out += ('' if (d == 1 and name) else digits[d]) + name
    return out


